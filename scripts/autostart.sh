#!/bin/sh
# dwm-tudor autostart — single unified autostart script
# Phase 1: Blocking setup (must complete before windows appear)
# Phase 2: Background services (compositor, notifications, polybar, tray apps)

# ── Run-once guard ─────────────────────────────────────────────────────────────
# autostart.sh can be started twice: by dwm-session AND by dwm's own
# runautostart(). Mark the X server (root window property, gone when X exits)
# so the second caller exits instead of starting every daemon again.
_claim() {
    if xprop -root DWM_AUTOSTARTED 2>/dev/null | grep -q '"1"'; then
        return 1
    fi
    xprop -root -f DWM_AUTOSTARTED 8s -set DWM_AUTOSTARTED 1
}
if command -v xprop >/dev/null 2>&1; then
    if command -v flock >/dev/null 2>&1; then
        ( flock 9; _claim ) 9>"${XDG_RUNTIME_DIR:-/tmp}/dwm-autostart-$(id -u).lock" || exit 0
    else
        _claim || exit 0
    fi
fi

# ── Phase 1: Blocking ──────────────────────────────────────────────────────────
# Disable DPMS and screen blanking (prevents GPU/display wake issues)
xset s off
xset s noblank
xset -dpms

# Export display env to systemd/dbus in parallel (both are IPC round-trips)
if command -v systemctl >/dev/null 2>&1; then
    systemctl --user import-environment DISPLAY XAUTHORITY &
fi
dbus-update-activation-environment --systemd DISPLAY XAUTHORITY 2>/dev/null &
wait

# ── Phase 2: Background services ───────────────────────────────────────────────


# Source theme environment so tray apps (e.g. flameshot) inherit QT_QPA_PLATFORMTHEME
# This file is generated by theme-apply.sh and updated on every theme change.
for _d in dwm-tudor dwm-titus; do
    THEME_ENV="${XDG_CONFIG_HOME:-$HOME/.config}/$_d/theme-env.sh"
    [ -f "$THEME_ENV" ] && { . "$THEME_ENV"; break; }
done

# Wallpaper (moved here from Phase 1 — does not need to block dwm startup)
feh --randomize --bg-fill ~/Pictures/backgrounds/* 2>/dev/null &

# Compositor
picom -b --backend glx 2>/dev/null &

# Notification daemon
dunst 2>/dev/null &

# Polkit authentication agent (try common agents)
for agent in \
    /usr/lib/mate-polkit/polkit-mate-authentication-agent-1 \
    /usr/lib/*/mate-polkit/polkit-mate-authentication-agent-1 \
    /usr/libexec/polkit-mate-authentication-agent-1 \
    /usr/lib/polkit-gnome/polkit-gnome-authentication-agent-1 \
    /usr/libexec/polkit-gnome-authentication-agent-1 \
    /usr/lib/polkit-kde-authentication-agent-1 \
    /usr/libexec/polkit-kde-authentication-agent-1 \
    /usr/bin/lxpolkit \
    /usr/lib/lxpolkit/lxpolkit; do
    if [ -x "$agent" ]; then
        "$agent" &
        break
    fi
done

# Launch Polybar
# dwm already starts polybar from setup() (spawnbar); only start it here if it is missing
pgrep -u "$(id -u)" -x polybar >/dev/null 2>&1 || "$HOME/.config/polybar/launch.sh" 2>/dev/null &
flameshot &

dex -a 2>/dev/null
command -v setxkbmap >/dev/null 2>&1 && setxkbmap -layout us,ro -variant ,std -option grp:alt_shift_toggle
