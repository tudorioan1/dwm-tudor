#!/bin/bash
# theme-apply.sh — Apply the active theme from themes.toml to all apps.
#
# Called automatically by DWM on config reload (SIGUSR1 / file save).
# Can also be run manually: theme-apply.sh
#
# Updates: alacritty · kitty · ghostty · rofi · polybar

# dwm starts this script through /bin/sh, which is dash on Debian/Ubuntu: dash has no
# `set -o pipefail` and no [[ ]], so it died on line 1 and nothing but the dwm bar
# changed. These two lines are plain POSIX sh: re-run under bash if we are not in it.
[ -n "${BASH_VERSION:-}" ] || exec bash "$0" "$@"

set -euo pipefail

# ── Locate themes.toml ────────────────────────────────────────────────────────
CFG_ROOT="${XDG_CONFIG_HOME:-$HOME/.config}"
DWM_CFG="$CFG_ROOT/dwm-tudor"
# fall back to the pre-rename directory if it has not been migrated yet
[[ -d "$DWM_CFG" ]] || { [[ -d "$CFG_ROOT/dwm-titus" ]] && DWM_CFG="$CFG_ROOT/dwm-titus"; }
THEMES_FILE="$DWM_CFG/themes.toml"
if [[ ! -f "$THEMES_FILE" ]]; then
    echo "theme-apply: themes.toml not found at $THEMES_FILE" >&2
    exit 1
fi

# ── Minimal TOML section reader ───────────────────────────────────────────────
# toml_get SECTION KEY FILE — prints the value or empty string
toml_get() {
    local section="$1" key="$2" file="$3"
    awk -v sec="[$section]" -v key="$key" '
        /^\[/ { in_sec = ($0 == sec) }
        in_sec && $0 ~ "^[[:space:]]*" key "[[:space:]]*=" {
            sub(/^[^=]*=[[:space:]]*/, "")
            gsub(/"/, "")
            gsub(/[[:space:]]+#.*$/, "")  # strip inline comments (not # in hex colors)
            sub(/[[:space:]]+$/, "")
            print; exit
        }
    ' "$file"
}

# ── Read active theme name ────────────────────────────────────────────────────
THEME_NAME="$(toml_get "active" "theme" "$THEMES_FILE")"
if [[ -z "$THEME_NAME" ]]; then
    echo "theme-apply: no [active] theme set in $THEMES_FILE" >&2
    exit 1
fi

SECTION="theme.$THEME_NAME"

# ── Helper: read a value from the active theme section ───────────────────────
theme_get() {
    toml_get "$SECTION" "$1" "$THEMES_FILE"
}

# ── Read all theme values ─────────────────────────────────────────────────────
TERM_BG="$(theme_get term_bg)"
TERM_FG="$(theme_get term_fg)"
TERM_CURSOR="$(theme_get term_cursor)"
TERM_C0="$(theme_get term_color0)"
TERM_C1="$(theme_get term_color1)"
TERM_C2="$(theme_get term_color2)"
TERM_C3="$(theme_get term_color3)"
TERM_C4="$(theme_get term_color4)"
TERM_C5="$(theme_get term_color5)"
TERM_C6="$(theme_get term_color6)"
TERM_C7="$(theme_get term_color7)"
TERM_C8="$(theme_get term_color8)"
TERM_C9="$(theme_get term_color9)"
TERM_C10="$(theme_get term_color10)"
TERM_C11="$(theme_get term_color11)"
TERM_C12="$(theme_get term_color12)"
TERM_C13="$(theme_get term_color13)"
TERM_C14="$(theme_get term_color14)"
TERM_C15="$(theme_get term_color15)"

GHOSTTY_THEME="$(theme_get ghostty_theme)"
ROFI_THEME="$(theme_get rofi_theme)"

PB_BG="$(theme_get polybar_bg)"
PB_FG="$(theme_get polybar_fg)"
PB_BG_ALT="$(theme_get polybar_bg_alt)"
PB_FG_ALT="$(theme_get polybar_fg_alt)"
PB_ACCENT="$(theme_get polybar_accent)"
PB_URGENT="$(theme_get polybar_urgent)"

DARK_MODE="$(theme_get dark_mode)"
[[ "$DARK_MODE" != "false" ]] && DARK_MODE="true"  # default to dark if unset


# ══════════════════════════════════════════════════════════════════════════════
# ALACRITTY — write ~/.config/alacritty/active-theme.toml
# ══════════════════════════════════════════════════════════════════════════════
ALACRITTY_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/alacritty"
if [[ -d "$ALACRITTY_DIR" ]]; then
    cat > "$ALACRITTY_DIR/active-theme.toml" <<EOF
# Auto-generated by theme-apply.sh — do not edit manually.
# Change the theme in ~/.config/dwm-tudor/themes.toml instead.

[colors.primary]
background = '$TERM_BG'
foreground = '$TERM_FG'

[colors.cursor]
text   = '$TERM_BG'
cursor = '$TERM_CURSOR'

[colors.normal]
black   = '$TERM_C0'
red     = '$TERM_C1'
green   = '$TERM_C2'
yellow  = '$TERM_C3'
blue    = '$TERM_C4'
magenta = '$TERM_C5'
cyan    = '$TERM_C6'
white   = '$TERM_C7'

[colors.bright]
black   = '$TERM_C8'
red     = '$TERM_C9'
green   = '$TERM_C10'
yellow  = '$TERM_C11'
blue    = '$TERM_C12'
magenta = '$TERM_C13'
cyan    = '$TERM_C14'
white   = '$TERM_C15'
EOF

    # Ensure alacritty.toml imports active-theme.toml (add if missing)
    if [[ -f "$ALACRITTY_DIR/alacritty.toml" ]]; then
        if ! grep -q "active-theme.toml" "$ALACRITTY_DIR/alacritty.toml"; then
            # Insert active-theme.toml as first import entry
            sed -i 's|^\(import = \[\s*\)|\1\n  "~/.config/alacritty/active-theme.toml",|' \
                "$ALACRITTY_DIR/alacritty.toml"
        fi
        # Replace any existing theme import line to point to active-theme.toml
        # (removes old theme-specific imports, keeps keybinds import)
        sed -i 's|"~/.config/alacritty/[^k][^"]*\.toml"|"~/.config/alacritty/active-theme.toml"|g' \
            "$ALACRITTY_DIR/alacritty.toml"
    fi
fi


# ══════════════════════════════════════════════════════════════════════════════
# KITTY — write ~/.config/kitty/active-theme.conf
# ══════════════════════════════════════════════════════════════════════════════
KITTY_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/kitty"
if [[ -d "$KITTY_DIR" ]]; then
    cat > "$KITTY_DIR/active-theme.conf" <<EOF
# Auto-generated by theme-apply.sh — do not edit manually.
# Change the theme in ~/.config/dwm-tudor/themes.toml instead.

background  $TERM_BG
foreground  $TERM_FG
cursor      $TERM_CURSOR

color0  $TERM_C0
color1  $TERM_C1
color2  $TERM_C2
color3  $TERM_C3
color4  $TERM_C4
color5  $TERM_C5
color6  $TERM_C6
color7  $TERM_C7
color8  $TERM_C8
color9  $TERM_C9
color10 $TERM_C10
color11 $TERM_C11
color12 $TERM_C12
color13 $TERM_C13
color14 $TERM_C14
color15 $TERM_C15
EOF

    # Ensure kitty.conf has 'include active-theme.conf' at the top
    if [[ -f "$KITTY_DIR/kitty.conf" ]]; then
        if ! grep -q "include active-theme.conf" "$KITTY_DIR/kitty.conf"; then
            sed -i '1s|^|include active-theme.conf\n|' "$KITTY_DIR/kitty.conf"
        fi
    fi

    # Signal kitty to reload (no restart needed)
    if command -v kitty &>/dev/null; then
        kill -SIGUSR1 "$(pgrep -x kitty)" 2>/dev/null || true
    fi
fi


# ══════════════════════════════════════════════════════════════════════════════
# GHOSTTY — update ~/.config/ghostty/config
# ══════════════════════════════════════════════════════════════════════════════
GHOSTTY_CFG="${XDG_CONFIG_HOME:-$HOME/.config}/ghostty/config"
# Ensure custom themes shipped with dwm-tudor are present
GHOSTTY_THEMES_SRC="$HOME/.local/share/dwm-tudor/ghostty/themes"
GHOSTTY_THEMES_DST="${XDG_CONFIG_HOME:-$HOME/.config}/ghostty/themes"
if [[ -d "$GHOSTTY_THEMES_SRC" ]]; then
    mkdir -p "$GHOSTTY_THEMES_DST"
    cp -r "$GHOSTTY_THEMES_SRC/"* "$GHOSTTY_THEMES_DST/" 2>/dev/null || true
fi
if [[ -n "$GHOSTTY_THEME" && -f "$GHOSTTY_CFG" ]]; then
    if grep -q "^theme[[:space:]]*=" "$GHOSTTY_CFG"; then
        sed -i "s|^theme[[:space:]]*=.*|theme = $GHOSTTY_THEME|" "$GHOSTTY_CFG"
    else
        echo "theme = $GHOSTTY_THEME" >> "$GHOSTTY_CFG"
    fi
    # The named theme controls the colours, except the background: it comes from term_bg so every
    # terminal gets the same (darker, theme-tinted) background. Manual foreground lines are dropped.
    sed -i '/^background[[:space:]]*=[^=]/d' "$GHOSTTY_CFG"
    sed -i '/^foreground[[:space:]]*=[^=]/d' "$GHOSTTY_CFG"
    if [[ -n "$TERM_BG" ]]; then echo "background = $TERM_BG" >> "$GHOSTTY_CFG"; fi
fi


# ══════════════════════════════════════════════════════════════════════════════
# ROFI — update @theme line in ~/.config/rofi/config.rasi
# ══════════════════════════════════════════════════════════════════════════════
ROFI_CFG="${XDG_CONFIG_HOME:-$HOME/.config}/rofi/config.rasi"
if [[ -n "$ROFI_THEME" && -f "$ROFI_CFG" ]]; then
    if grep -q '@theme' "$ROFI_CFG"; then
        sed -i "s|@theme \".*\"|@theme \"themes/$ROFI_THEME.rasi\"|g" "$ROFI_CFG"
    else
        echo "@theme \"themes/$ROFI_THEME.rasi\"" >> "$ROFI_CFG"
    fi
fi


# ══════════════════════════════════════════════════════════════════════════════
# POLYBAR — fully replace ~/.config/polybar/themes/minimal/colors.ini
# ══════════════════════════════════════════════════════════════════════════════
PB_COLORS="${XDG_CONFIG_HOME:-$HOME/.config}/polybar/themes/minimal/colors.ini"
if [[ -n "$PB_BG" ]]; then
    mkdir -p "$(dirname "$PB_COLORS")"
    # Build the new file first; only replace it (and restart polybar) if it changed.
    # Volume bar ramp, red -> green. Dark themes keep the original rainbow; light themes get a deeper
    # one (the pastel yellows/greens of the rainbow are invisible on a light bar).
    if [[ "$DARK_MODE" == "true" ]]; then
        PB_VOL=(ff5555 ff7755 ff9955 ffbb55 ffdd55 ddff55 bbff55 99ff55 77ff55 55ff55)
    else
        PB_VOL=(e63737 da471b ba6317 9f7414 847b10 718410 5a8811 408d11 248d11 118d1c)
    fi
    PB_VOL_LINES=""
    for i in "${!PB_VOL[@]}"; do PB_VOL_LINES+="vol-$i = #${PB_VOL[$i]}"$'\n'; done
    PB_NEW="$(mktemp)"
    cat > "$PB_NEW" <<EOF
# Auto-generated by theme-apply.sh — do not edit manually.
# Change the theme in ~/.config/dwm-tudor/themes.toml instead.

[colors]
bg               = $PB_BG
fg               = $PB_FG
bg-alt           = $PB_BG_ALT
fg-alt           = $PB_FG_ALT

blue             = $PB_ACCENT
red              = $PB_URGENT

; These values are computed from the theme's terminal palette.
; Polybar modules that reference \${colors.cyan}, \${colors.green} etc. will
; fall back to the accent/urgent colours above if a theme doesn't define them.
cyan             = $PB_ACCENT
green            = $PB_ACCENT
orange           = $PB_URGENT
pink             = $PB_ACCENT
purple           = $PB_ACCENT
yellow           = $PB_ACCENT

black            = $PB_BG
white            = $PB_FG

trans            = #00000000
semi-trans-black = #aa000000

; Volume bar ramp (see pulseaudio.ini)
${PB_VOL_LINES}
EOF

    if cmp -s "$PB_NEW" "$PB_COLORS" 2>/dev/null; then
        rm -f "$PB_NEW"   # unchanged -> no needless polybar restart (dwm runs this at every start)
    else
    cat "$PB_NEW" > "$PB_COLORS"; rm -f "$PB_NEW"
    # Restart polybar to pick up the new colors
    if command -v polybar &>/dev/null; then
        POLYBAR_LAUNCH="${XDG_CONFIG_HOME:-$HOME/.config}/polybar/launch.sh"
        if [[ -x "$POLYBAR_LAUNCH" ]]; then
            "$POLYBAR_LAUNCH" &
        fi
    fi
    fi
fi


# ══════════════════════════════════════════════════════════════════════════════
# DUNST (notifications) — colours follow the theme
# ══════════════════════════════════════════════════════════════════════════════
# dunstrc used to carry fixed colours (always near-black). Rewrite only the colour keys, in the
# [global] and [urgency_*] sections, from the same palette as the Polybar; everything else in
# the file is left untouched. A read-only dunstrc must never abort the script.
apply_dunst_theme() {
    local rc="${XDG_CONFIG_HOME:-$HOME/.config}/dunst/dunstrc" new
    [[ -f "$rc" ]] || return 0
    [[ -n "$PB_BG" && -n "$PB_FG" && -n "$PB_ACCENT" && -n "$PB_FG_ALT" && -n "$PB_URGENT" ]] || return 0
    new="$(mktemp)"
    local icons="Papirus-Dark"; [[ "$DARK_MODE" == "true" ]] || icons="Papirus-Light"
    awk -v bg="$PB_BG" -v fg="$PB_FG" -v accent="$PB_ACCENT" -v dim="$PB_FG_ALT" -v urgent="$PB_URGENT" -v icons="$icons" '
        function key(l,   k) { k = l; sub(/^[ \t]*/, "", k); sub(/[ \t]*=.*$/, "", k); return k }
        /^\[/ { sec = $0; print; next }
        {
            k = key($0)
            if (sec == "[global]" && k == "icon_theme" && $0 ~ /Papirus/) { print "    icon_theme = " icons; next }
            if (sec == "[global]" && k == "frame_color") { print "frame_color = \"" accent "\""; next }
            if (sec == "[urgency_low]" || sec == "[urgency_normal]") {
                fc = (sec == "[urgency_low]") ? dim : accent
                if (k == "background") { print "    background = \"" bg "\""; print "    frame_color = \"" fc "\""; next }
                if (k == "foreground") { print "    foreground = \"" fg "\""; next }
                if (k == "frame_color") next
            }
            if (sec == "[urgency_critical]") {
                if (k == "background") { print "    background = \"" bg "\""; next }
                if (k == "foreground") { print "    foreground = \"" urgent "\""; next }
                if (k == "frame_color") { print "    frame_color = \"" urgent "\""; next }
            }
            print
        }' "$rc" > "$new"
    if [[ -s "$new" ]] && ! cmp -s "$new" "$rc"; then
        cat "$new" > "$rc"
        # apply to the running daemon (dunstctl reload, else restart it)
        if pgrep -u "$(id -u)" -x dunst >/dev/null 2>&1; then
            dunstctl reload 2>/dev/null || { pkill -u "$(id -u)" -x dunst; setsid dunst >/dev/null 2>&1 & }
        fi
    fi
    rm -f "$new"
}
apply_dunst_theme || echo "theme-apply: could not update dunstrc - skipped" >&2

# ══════════════════════════════════════════════════════════════════════════════
# GTK DARK / LIGHT MODE
# ══════════════════════════════════════════════════════════════════════════════
if [[ "$DARK_MODE" == "true" ]]; then
    GTK_COLOR_SCHEME="prefer-dark"
    GTK_THEME_NAME="Adwaita-dark"
    GTK_DARK_PREF=1
else
    GTK_COLOR_SCHEME="default"
    GTK_THEME_NAME="Adwaita"
    GTK_DARK_PREF=0
fi

# Helper: set or add a key in a [Settings] ini file without destroying other settings
gtk_ini_set() {
    local file="$1" key="$2" value="$3"
    mkdir -p "$(dirname "$file")"
    if [[ ! -f "$file" ]]; then
        printf '[Settings]\n%s=%s\n' "$key" "$value" > "$file"
        return
    fi
    if grep -q "^${key}" "$file"; then
        sed -i "s|^${key}=.*|${key}=${value}|" "$file"
    elif grep -q '^\[Settings\]' "$file"; then
        sed -i "/^\[Settings\]/a ${key}=${value}" "$file"
    else
        printf '\n[Settings]\n%s=%s\n' "$key" "$value" >> "$file"
    fi
}

# Helper: same for ~/.gtkrc-2.0 (key="value" lines), keeping every other line
gtkrc_set() {
    local file="$HOME/.gtkrc-2.0" key="$1" value="$2"
    if [[ -f "$file" ]] && grep -q "^${key}=" "$file"; then
        sed -i "s|^${key}=.*|${key}=\"${value}\"|" "$file"
    else
        printf '%s="%s"\n' "$key" "$value" >> "$file"
    fi
}

# A read-only or immutable file (chattr +i, read-only dotfiles) must not abort the whole script:
# the Qt step below still has to run. Say so and carry on.
gtk_try() { "$@" || echo "theme-apply: '$*' failed (read-only or immutable file?) - skipped" >&2; }

GTK3_INI="${XDG_CONFIG_HOME:-$HOME/.config}/gtk-3.0/settings.ini"
GTK4_INI="${XDG_CONFIG_HOME:-$HOME/.config}/gtk-4.0/settings.ini"

# The GTK theme NAME is only managed here while it is unset or one of the stock Adwaita pair.
# Once the user has picked another theme (nwg-look, or the installer's GTK step) it is left
# alone: it used to be reset to Adwaita on every login and theme switch, so a chosen theme
# never survived a restart. The dark/light PREFERENCE is still synced either way.
CURRENT_GTK_THEME="$(sed -n 's/^gtk-theme-name=//p' "$GTK3_INI" 2>/dev/null | head -n1 || true)"
case "$CURRENT_GTK_THEME" in
    ""|Adwaita|Adwaita-dark) MANAGE_GTK_NAME=1 ;;
    *)                       MANAGE_GTK_NAME=0 ;;
esac

# Is a GTK / icon theme installed?  <themes|icons> <name>
theme_dir_exists() {
    local d
    for d in "$HOME/.local/share/$1/$2" "$HOME/.$1/$2" "/usr/share/$1/$2" "/usr/local/share/$1/$2"; do
        [[ -d "$d" ]] && return 0
    done
    return 1
}

# Set the GTK theme / icon theme everywhere GTK looks (GTK3, GTK4, GTK2, GSettings)
set_gtk_theme_name() {
    gtk_try gtk_ini_set "$GTK3_INI" "gtk-theme-name" "$1"
    gtk_try gtk_ini_set "$GTK4_INI" "gtk-theme-name" "$1"
    gtk_try gtkrc_set "gtk-theme-name" "$1"
    if command -v gsettings &>/dev/null; then
        gsettings set org.gnome.desktop.interface gtk-theme "$1" 2>/dev/null || true
    fi
}
set_gtk_icon_name() {
    gtk_try gtk_ini_set "$GTK3_INI" "gtk-icon-theme-name" "$1"
    gtk_try gtk_ini_set "$GTK4_INI" "gtk-icon-theme-name" "$1"
    gtk_try gtkrc_set "gtk-icon-theme-name" "$1"
    if command -v gsettings &>/dev/null; then
        gsettings set org.gnome.desktop.interface icon-theme "$1" 2>/dev/null || true
    fi
}

# GTK3 / GTK4 dark/light preference
gtk_try gtk_ini_set "$GTK3_INI" "gtk-application-prefer-dark-theme" "$GTK_DARK_PREF"
gtk_try gtk_ini_set "$GTK4_INI" "gtk-application-prefer-dark-theme" "$GTK_DARK_PREF"
if [[ "$MANAGE_GTK_NAME" == 1 ]]; then
    set_gtk_theme_name "$GTK_THEME_NAME"
fi

# Follow dark/light for the theme families that ship both variants (Materia, Papirus): on a light
# theme the dark variants give a dark app next to a light bar and white tray icons that vanish on it.
# Anything else the user picked is left alone, and a variant that is not installed is never selected.
if [[ "$DARK_MODE" == "true" ]]; then
    WANT_GTK_THEME="Materia-dark";  WANT_ICON_THEME="Papirus-Dark"
else
    WANT_GTK_THEME="Materia-light"; WANT_ICON_THEME="Papirus-Light"
fi
case "$CURRENT_GTK_THEME" in
    Materia|Materia-dark|Materia-light)
        if [[ "$CURRENT_GTK_THEME" != "$WANT_GTK_THEME" ]] && theme_dir_exists themes "$WANT_GTK_THEME"; then
            set_gtk_theme_name "$WANT_GTK_THEME"
        fi ;;
esac
CURRENT_ICON_THEME="$(sed -n 's/^gtk-icon-theme-name=//p' "$GTK3_INI" 2>/dev/null | head -n1 || true)"
case "$CURRENT_ICON_THEME" in
    Papirus|Papirus-Dark|Papirus-Light)
        if [[ "$CURRENT_ICON_THEME" != "$WANT_ICON_THEME" ]] && theme_dir_exists icons "$WANT_ICON_THEME"; then
            set_gtk_icon_name "$WANT_ICON_THEME"
        fi ;;
esac

# Live D-Bus update — affects running GTK4 apps, Flatpaks, and XDG portals
if command -v gsettings &>/dev/null; then
    gsettings set org.gnome.desktop.interface color-scheme "$GTK_COLOR_SCHEME" 2>/dev/null || true
fi


# ══════════════════════════════════════════════════════════════════════════════
# QT DARK / LIGHT MODE
# ══════════════════════════════════════════════════════════════════════════════
# Prefer qt6ct > qt5ct; fall back to gtk3 (inherits GTK theme set above)
if command -v qt6ct &>/dev/null; then
    QT_PLATFORM_THEME="qt6ct"
elif command -v qt5ct &>/dev/null; then
    QT_PLATFORM_THEME="qt5ct"
else
    QT_PLATFORM_THEME="gtk3"
fi

# Write persistent env file — sourced by autostart.sh so tray apps inherit it
THEME_ENV_FILE="$DWM_CFG/theme-env.sh"
mkdir -p "$DWM_CFG"
cat > "$THEME_ENV_FILE" <<EOF
# Auto-generated by theme-apply.sh — do not edit manually.
export QT_QPA_PLATFORMTHEME=$QT_PLATFORM_THEME
EOF

# Update qt5ct / qt6ct color scheme config if that tool is the active theme
if [[ "$QT_PLATFORM_THEME" == "qt5ct" || "$QT_PLATFORM_THEME" == "qt6ct" ]]; then
    QT_CT_CONF="${XDG_CONFIG_HOME:-$HOME/.config}/${QT_PLATFORM_THEME}/${QT_PLATFORM_THEME}.conf"
    if [[ -f "$QT_CT_CONF" ]]; then
        if [[ "$DARK_MODE" == "true" ]]; then
            QT_CT_SCHEME="/usr/share/${QT_PLATFORM_THEME}/colors/darker.conf"
        else
            QT_CT_SCHEME=""
        fi
        if grep -q '^color_scheme_path' "$QT_CT_CONF"; then
            sed -i "s|^color_scheme_path=.*|color_scheme_path=$QT_CT_SCHEME|" "$QT_CT_CONF"
        else
            sed -i "/^\[Appearance\]/a color_scheme_path=${QT_CT_SCHEME}" "$QT_CT_CONF"
        fi
    fi
fi

# Propagate to D-Bus-activated services already running in this session
if command -v dbus-update-activation-environment &>/dev/null; then
    dbus-update-activation-environment QT_QPA_PLATFORMTHEME="$QT_PLATFORM_THEME" 2>/dev/null || true
fi

# Restart flameshot so its tray icon picks up the new theme
if pgrep -x flameshot &>/dev/null; then
    pkill -x flameshot 2>/dev/null || true
    sleep 0.3
    QT_QPA_PLATFORMTHEME="$QT_PLATFORM_THEME" flameshot &
fi


echo "theme-apply: applied theme '$THEME_NAME'"
